"""Regenerate `docs/PYRIGHT-BASELINE.md` and `pyright-baseline.json`: the type debt.

pyright has no per-file allowlist, so the ratchet works differently: the committed
fingerprint lists every `path -> {code: count}`, and `--check` fails when the tree produces
a hit that is not in it. Debt may shrink at any time; it may only grow on purpose.

    python -m scripts.pyright_baseline            # rewrite both files
    python -m scripts.pyright_baseline --check    # exit 1 on new debt or a stale document
"""

from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "PYRIGHT-BASELINE.md"
FINGERPRINT = ROOT / "pyright-baseline.json"


def run_pyright() -> str:
    """pyright's JSON report (`--outputjson`), as text.

    The plain text output only prints the rule name for some diagnostics, so the JSON
    report is the only place that says which rule fired.
    """
    done = subprocess.run(
        [sys.executable, "-m", "pyright", "--outputjson"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return done.stdout or done.stderr or ""


def _relative(path: str) -> str:
    """Trim a diagnostics path to its repo-relative form."""
    for anchor in ("finscrape/", "server/", "worker/", "tests/", "scripts/", "web/"):
        index = path.find(f"/{anchor}")
        if index != -1:
            return path[index + 1 :]
    return path


def parse_fingerprint(output: str) -> dict[str, dict[str, int]]:
    """`{relative path: {reportCode: count}}` for every error pyright reported.

    Line and column numbers are deliberately dropped: they move on every unrelated edit and
    would make the fingerprint churn. A new *kind* of error in a file, or a higher count of
    one, still registers.
    """
    try:
        report = json.loads(output)
    except json.JSONDecodeError:
        return {}
    found: dict[str, Counter[str]] = {}
    for diagnostic in report.get("generalDiagnostics", []):
        if diagnostic.get("severity") != "error":
            continue
        path = Path(diagnostic.get("file", "")).as_posix()
        rel = _relative(path)
        code = diagnostic.get("rule") or "unreported"
        found.setdefault(rel, Counter())[code] += 1
    return {path: dict(codes) for path, codes in sorted(found.items())}


def total(fingerprint: dict[str, dict[str, int]]) -> int:
    return sum(sum(codes.values()) for codes in fingerprint.values())


def new_hits(
    baseline: dict[str, dict[str, int]], current: dict[str, dict[str, int]]
) -> list[str]:
    """Every (path, code) that the tree has more of than the baseline allows."""
    out = []
    for path, codes in current.items():
        allowed = baseline.get(path, {})
        for code, count in sorted(codes.items()):
            if count > allowed.get(code, 0):
                out.append(f"{path}: {code} x{count} (baseline {allowed.get(code, 0)})")
    return out


def render(fingerprint: dict[str, dict[str, int]]) -> str:
    paths = sorted(fingerprint)
    codes: Counter[str] = Counter()
    for hits in fingerprint.values():
        codes.update(hits)
    lines = [
        "# Pyright baseline",
        "",
        "Generated by `make pyright-baseline` (`python -m scripts.pyright_baseline`). Do not",
        "edit by hand. pyright runs over the whole tree in `basic` mode; the committed",
        "fingerprint in `pyright-baseline.json` lists the type debt that already existed, and",
        "`--check` fails when the tree produces a hit that is not in it. Debt may shrink freely",
        "and may only grow on purpose (plan m1.2.2).",
        "",
        f"**{total(fingerprint)} errors in {len(paths)} files.**",
        "",
        "## By rule",
        "",
        "| Count | Code |",
        "|---|---|",
    ]
    lines += [f"| {count} | `{code}` |" for code, count in codes.most_common()]
    lines += ["", "## By file", "", "| Count | Path | Codes |", "|---|---|---|"]
    for path in paths:
        hits = fingerprint[path]
        summary = ", ".join(f"`{code}`×{n}" for code, n in sorted(hits.items()))
        lines.append(f"| {sum(hits.values())} | `{path}` | {summary} |")
    lines += [
        "",
        "## Scope",
        "",
        "- `server/`, `worker/`, `finscrape/` — everything the app imports. Tests are not",
        "  type-checked yet.",
        "- `finscrape/absorbed/` is excluded: vendored reference code, not wired in.",
        "",
    ]
    return "\n".join(lines)


def generate(write: bool) -> list[str]:
    output = run_pyright()
    current = parse_fingerprint(output)
    baseline = (
        json.loads(FINGERPRINT.read_text(encoding="utf-8"))
        if FINGERPRINT.is_file()
        else {}
    )
    stale = []
    doc = render(current)
    if not DOC.is_file() or DOC.read_text(encoding="utf-8") != doc:
        stale.append(str(DOC.relative_to(ROOT)))
    body = json.dumps(current, indent=2, sort_keys=True) + "\n"
    if not FINGERPRINT.is_file() or FINGERPRINT.read_text(encoding="utf-8") != body:
        stale.append(str(FINGERPRINT.relative_to(ROOT)))
    if write:
        DOC.write_text(doc, encoding="utf-8", newline="\n")
        FINGERPRINT.write_text(body, encoding="utf-8", newline="\n")
        return stale
    return [*stale, *new_hits(baseline, current)]


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    stale = generate(write="--check" not in args)
    for item in stale:
        verb = "stale" if "--check" in args else "wrote"
        print(f"pyright_baseline: {verb} {item}", file=sys.stderr)
    return 1 if (stale and "--check" in args) else 0


if __name__ == "__main__":
    raise SystemExit(main())
