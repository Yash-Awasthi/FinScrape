"""Regenerate `docs/RUFF-BASELINE.md`: the ruff debt, grouped by rule and by directory.

The baseline is a ratchet. `make ruff-baseline` rewrites it, and the test in
`tests/test_docs.py` fails when the file and the tree disagree, so the numbers can only
move when someone regenerates them on purpose — and the rule groups below are burned
down one per pull request (plan m1.2.1/m1.2.3).

    python -m scripts.ruff_baseline            # rewrite the file
    python -m scripts.ruff_baseline --check    # exit 1 if the file is stale
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "RUFF-BASELINE.md"
IGNORES = ROOT / "ruff-baseline.toml"

sys.path.insert(0, str(ROOT))
from scripts.repo_facts import tracked_python_files

STAT_LINE = re.compile(r"^(\d+)\s+(\w+)\s+(\[[^\]]\])\s+(\S+)$")


# The allowlist above rewrites what ruff reports, so every measurement here runs with it
# disabled — otherwise the baseline would count only the debt it has not yet frozen.
NO_ALLOWLIST = ["--config", "lint.per-file-ignores={}"]

# Codes ruff fires on code that is correct. They stay allowed in `ruff-baseline.toml` so the
# gate does not trip on them, but they are not debt and are not counted as debt. Each entry
# needs a reason and a test that keeps it true (see `tests/test_docs.py`).
FALSE_POSITIVES = {
    "F811": (
        "every hit is an `@overload` stub or the implementation that follows it; "
        "guarded by `test_f811_only_fires_on_overloads`"
    ),
}


def is_false_positive(line: str) -> bool:
    """True for a concise-output line whose code is a known false positive."""
    parts = line.split(":")
    return (
        len(parts) >= 4
        and parts[0].endswith(".py")
        and parts[3].strip().split()[0] in FALSE_POSITIVES
    )


def _ruff(args: list[str]) -> str:
    done = subprocess.run(
        [sys.executable, "-m", "ruff", "check", ".", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    return done.stdout


def per_rule(statistics: str, concise: str) -> list[tuple[str, str, int, str]]:
    """[(code, rule name, occurrences, fix marker)] for real debt only.

    A `--statistics` line looks like `86\tF401   \t[-]\tunused-import`: `[*]` is autofixable,
    `[-]` has a fix ruff calls unsafe, and an empty marker means there is no fix. Counts come
    from the concise output so that known false positives can be dropped from them.
    """
    markers = {}
    names = {}
    for line in statistics.splitlines():
        match = STAT_LINE.match(line.strip())
        if match:
            _, code, marker, name = match.groups()
            markers[code] = marker
            names[code] = name
    counts: Counter[str] = Counter()
    for line in concise.splitlines():
        parts = line.split(":")
        if len(parts) >= 4 and parts[0].endswith(".py"):
            counts[parts[3].strip().split()[0]] += 1
    return [
        (code, names.get(code, ""), count, markers.get(code, ""))
        for code, count in counts.most_common()
    ]


def per_dir(concise: str) -> list[tuple[str, int]]:
    """Errors per top-level (or second-level) directory, biggest first."""
    counts: Counter[str] = Counter()
    for line in concise.splitlines():
        head = line.split(":", 1)[0].replace("\\", "/")
        if not head.endswith(".py"):
            continue
        parts = head.split("/")
        counts["/".join(parts[:2]) if len(parts) > 2 else head] += 1
    return counts.most_common()


def total_errors(concise: str) -> int:
    return sum(1 for line in concise.splitlines() if line.strip() and ".py:" in line)


def render(statistics: str, concise: str) -> str:
    """The markdown table. `concise` must already have the false positives removed."""
    rows = per_rule(statistics, concise)
    total = total_errors(concise)
    files = {line.split(":", 1)[0] for line in concise.splitlines() if ".py:" in line}
    fixable = sum(1 for _, _, _, marker in rows if marker == "[*]")
    dirs = per_dir(concise)
    summary = (
        f"**{total} errors in {len(files)} files of {len(tracked_python_files())} tracked "
        f"Python files.** {len(rows)} rule codes; {fixable} of them have an autofix."
    )
    lines = [
        "# Ruff baseline",
        "",
        "Generated by `make ruff-baseline` (`python -m scripts.ruff_baseline`). Do not edit by",
        "hand. This file is a ratchet: the totals below may only shrink, and each pull request",
        "burns down one rule group (plan m1.2.1). `tests/test_docs.py` fails when this file and",
        "the tree disagree, so a change to lint debt has to regenerate it.",
        "",
        summary,
        "",
        "## By rule",
        "",
        "| Count | Code | Rule | Autofix |",
        "|---|---|---|---|",
    ]
    for code, name, count, marker in rows:
        fix = {"[*]": "yes", "[-]": "unsafe only"}.get(marker, "no")
        lines.append(f"| {count} | `{code}` | {name} | {fix} |")
    lines += ["", "## By directory", "", "| Count | Path |", "|---|---|"]
    lines += [f"| {count} | `{path}` |" for path, count in dirs]
    lines += [
        "",
        "## Known false positives",
        "",
        "Allowed in `ruff-baseline.toml`, not counted above, and guarded by a test so a real",
        "hit of the same code still fails:",
        "",
    ]
    lines += [f"- `{code}` — {reason}" for code, reason in FALSE_POSITIVES.items()]
    lines += [
        "",
        "## Excluded from every gate",
        "",
        "- `finscrape/absorbed/` — vendored reference code, excluded in `pyproject.toml`.",
        "- Nothing else: the scope is the whole tree, which is the point of M1.2.",
        "",
    ]
    return "\n".join(lines)


def per_file_ignores(concise: str) -> dict[str, list[str]]:
    """file -> the rule codes it is currently allowed to carry.

    This is the ratchet itself: `ruff check .` runs over the whole tree and fails on any
    error that is not already in this map, so new debt cannot land anywhere. Removing an
    entry (or a code from one) is how a rule group is burned down.
    """
    allowed: dict[str, set[str]] = {}
    for line in concise.splitlines():
        parts = line.split(":")
        if len(parts) < 4 or not parts[0].endswith(".py"):
            continue
        path = parts[0].replace("\\", "/")
        code = parts[3].strip().split()[0]
        allowed.setdefault(path, set()).add(code)
    return {path: sorted(codes) for path, codes in sorted(allowed.items())}


def render_ignores(concise: str) -> str:
    """`ruff-baseline.toml`, merged into pyproject via `[tool.ruff] extend`."""
    ignores = per_file_ignores(concise)
    lines = [
        "# Generated by `make ruff-baseline`. Do not edit by hand.",
        "#",
        "# Every line here is lint debt that already existed when the whole tree entered the",
        "# gate (plan m1.2.1). pyproject.toml extends this file, so `ruff check .` passes on the",
        "# tree as it stands and fails on anything new. Delete entries as files are cleaned up:",
        "# the file is a ratchet and must only ever shrink.",
        "",
        "[lint.per-file-ignores]",
    ]
    for path, codes in ignores.items():
        quoted = ", ".join(f'"{code}"' for code in codes)
        lines.append(f'"{path}" = [{quoted}]')
    return "\n".join(lines) + "\n"


def generate(write: bool) -> list[str]:
    """Rewrite both artefacts, or report that they are stale."""
    concise_all = _ruff([*NO_ALLOWLIST, "--output-format", "concise"])
    concise = "\n".join(
        line for line in concise_all.splitlines() if not is_false_positive(line)
    )
    wanted = {
        TARGET: render(_ruff([*NO_ALLOWLIST, "--statistics"]), concise),
        IGNORES: render_ignores(concise_all),
    }
    stale = []
    for path, body in wanted.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current == body:
            continue
        stale.append(str(path.relative_to(ROOT)))
        if write:
            path.write_text(body, encoding="utf-8", newline="\n")
    return stale


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    stale = generate(write="--check" not in args)
    for rel in stale:
        verb = "stale" if "--check" in args else "wrote"
        print(f"ruff_baseline: {verb} {rel}", file=sys.stderr)
    return 1 if (stale and "--check" in args) else 0


if __name__ == "__main__":
    raise SystemExit(main())
